const TF_OPTIONS = ['✓ عبارة صحيحة', '✗ عبارة خاطئة'];

function stableHash(text: string): number {
  let h = 0;
  for (let i = 0; i < text.length; i++) h = (h * 31 + text.charCodeAt(i)) >>> 0;
  return h;
}

function buildExam(spec: ExamSpec, n: number): AssessmentBlock[] {
  const prefix = `u2x${n}`;
  let q = 0;
  const nextId = () => `${prefix}-q${++q}`;

  const mcqs: Question[] = spec.mcqs.map(([text, written, writtenCorrect, why]) => {
    if (writtenCorrect < 0 || writtenCorrect >= written.length) throw new Error(`Bad answer index in model ${n}: ${text}`);
    // Spread correct answers over أ–د: swap the correct option into a slot derived from the question text
    // (stable across builds, so the letter in the explanation always matches what students see).
    const correct = stableHash(text) % written.length;
    const options = [...written];
    [options[correct], options[writtenCorrect]] = [options[writtenCorrect]!, options[correct]!];
    return {
      id: nextId(), type: 'mcq', difficulty: 'easy', text, options, correctAnswerIndex: correct,
      explanation: `الإجابة الصحيحة هي (${LETTERS[correct]}) ${options[correct]}. ${why}`
    };
  });

  const tf: Question[] = spec.tf.map(([text, isTrue, why]) => ({
    id: nextId(), type: 'mcq', difficulty: 'easy', text, options: TF_OPTIONS, correctAnswerIndex: isTrue ? 0 : 1,
    explanation: `${isTrue ? 'العبارة صحيحة.' : 'العبارة خاطئة.'} ${why}`
  }));

  const fix: EssayQuestion[] = spec.fix.map(([text, answer]) => ({
    id: nextId(), text, answer: [answer], marks: MARKS.fix
  }));

  const essays: EssayQuestion[] = spec.essays.map(([text, answer]) => ({
    id: nextId(), text, answer, marks: MARKS.essay
  }));

  const sections = [
    { count: mcqs.length, each: MARKS.mcq },
    { count: tf.length, each: MARKS.tf },
    { count: fix.length, each: MARKS.fix },
    { count: essays.length, each: MARKS.essay }
  ];
  const [mcqTotal, tfTotal, fixTotal, essayTotal] = sections.map(s => s.count * s.each) as [number, number, number, number];
  if (mcqTotal + tfTotal + fixTotal + essayTotal !== TOTAL_MARKS || mcqTotal + tfTotal !== OBJECTIVE_MARKS) {
    throw new Error(`Unit 2 model ${n}: objective ${mcqTotal + tfTotal} + written ${fixTotal + essayTotal}, expected ${OBJECTIVE_MARKS} + ${TOTAL_MARKS - OBJECTIVE_MARKS}`);
  }

  const period = (count: number, each: number) => `${count} أسئلة × ${marksLabel(each)} = ${marksLabel(count * each)}`;

  return [
    {
      id: `${prefix}-mcq`,
      period: period(mcqs.length, MARKS.mcq),
      title: `أولًا: اختر الإجابة الصحيحة (${marksLabel(mcqTotal)})`,
      quizTitle: `أولًا: اختر الإجابة الصحيحة (${marksLabel(MARKS.mcq)} لكل سؤال)`,
      essays: [],
      mcqs
    },
    {
      id: `${prefix}-tf`,
      period: period(tf.length, MARKS.tf),
      title: `ثانيًا: ضع علامة (✓) أو علامة (✗) (${marksLabel(tfTotal)})`,
      quizTitle: `ثانيًا: صح أم خطأ؟ (${marksLabel(MARKS.tf)} لكل سؤال)`,
      essays: [],
      mcqs: tf
    },
    {
      id: `${prefix}-fix`,
      period: period(fix.length, MARKS.fix),
      title: `ثالثًا: صحّح ما بين القوسين (${marksLabel(fixTotal)})`,
      essaysTitle: '✏️ صحّح ما بين القوسين «»',
      essays: fix,
      mcqs: []
    },
    {
      id: `${prefix}-essay`,
      period: period(essays.length, MARKS.essay),
      title: `رابعًا: أجب عما يأتي (${marksLabel(essayTotal)})`,
      essaysTitle: '✍️ الأسئلة المقالية',
      essays,
      mcqs: []
    }
  ];
}

